// 16x16 item icons: tools, seeds, crops and materials. Every item in src/data/items.js has one.
import { grid, set, line, blit, parse, outline, fillRect, ellipse } from './raster.js';

/** A wooden handle from (x0, y0) to (x1, y1): lit stroke with a darker underside. */
function handle(g, x0, y0, x1, y1) {
  line(g, x0, y0, x1, y1, 'wood4');
  line(g, x0 + 1, y0, x1 + 1, y1, 'wood2');
}

const STEEL = { a: 'stone4', b: 'stone3', c: 'stone2', d: 'stone1' };

function tool(headRows, hx, hy, hand = [2, 14, 11, 5]) {
  const g = grid(16, 16);
  handle(g, ...hand);
  blit(g, parse(headRows, STEEL), hx, hy);
  const o = outline(g, { color: 'ink0' });
  return cropTo16(o);
}

// outline() pads by 1px; trim back to 16x16 (our art keeps a 1px margin so nothing is lost).
function cropTo16(g) {
  const out = grid(16, 16);
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) out.px[y * 16 + x] = g.px[(y + 1) * g.w + x + 1];
  return out;
}


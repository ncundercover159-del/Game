/** Coin icon for money displays (mon: round with a square hole). */
export function coinIcon() {
  const g = grid(9, 9);
  ellipse(g, 4.5, 4.5, 4.5, 4.5, 'gold1');
  ellipse(g, 4, 4, 3.5, 3.5, 'gold2');
  fillRect(g, 3, 3, 3, 3, 'wood1');
  set(g, 2, 2, 'gold3');
  return g;
}

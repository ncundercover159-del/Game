export function t(key, vars) {
  let s = STRINGS[key];
  if (s === undefined) throw new Error(`Missing string "${key}"`);
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
  return s;
}
